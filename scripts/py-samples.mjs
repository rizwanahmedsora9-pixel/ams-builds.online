#!/usr/bin/env node
/**
 * Bakes samples/python/*.py into src/admin/py-samples.ts, so the editor's
 * "Start from a sample" list is the same code that the tests run.
 *
 *   node scripts/py-samples.mjs          # rewrite src/admin/py-samples.ts
 *   node scripts/py-samples.mjs --check  # exit 1 if it is out of date
 *
 * The samples directory stays the one place a sample is edited; tests/pyapp.test.mjs
 * runs every file there and also fails when the baked copy has gone stale.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'samples', 'python');
const OUT = join(ROOT, 'src', 'admin', 'py-samples.ts');

/** A short label for the picker: the file's own first comment, else the name. */
function title(file, code) {
  const first = (code.split('\n').find((line) => /^#\s*\S/.test(line)) || '').replace(/^#\s*/, '').trim();
  const fallback = file.replace(/^\d+-/, '').replace(/\.py$/, '').replace(/-/g, ' ');
  return (first || fallback).slice(0, 70);
}

const files = readdirSync(DIR).filter((name) => name.endsWith('.py')).sort();
if (!files.length) {
  console.error('samples/python holds no .py files; nothing to bake.');
  process.exit(1);
}

const rows = files.map((file) => {
  const code = readFileSync(join(DIR, file), 'utf8').replace(/\r\n?/g, '\n');
  const name = file.replace(/^\d+-/, '');
  return { name, title: title(file, code), code };
});

const body = `/**
 * The editor's Python samples, baked from samples/python/*.py.
 *
 * Generated by scripts/py-samples.mjs - edit the .py files, then run
 * "node scripts/py-samples.mjs". tests/pyapp.test.mjs checks that this file
 * matches the directory and runs every program here in a real interpreter.
 */
export type PythonSample = { name: string; title: string; code: string };

export const PYTHON_SAMPLES: PythonSample[] = ${JSON.stringify(rows, null, 2)};
`;

const current = (() => {
  try {
    return readFileSync(OUT, 'utf8');
  } catch {
    return '';
  }
})();

if (process.argv.includes('--check')) {
  if (current !== body) {
    console.error('src/admin/py-samples.ts is out of date: run node scripts/py-samples.mjs');
    process.exit(1);
  }
  console.log(`py-samples.ts matches ${rows.length} samples.`);
} else {
  writeFileSync(OUT, body);
  console.log(`Wrote ${OUT} from ${rows.length} samples.`);
}
